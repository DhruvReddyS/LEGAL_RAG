"""The privacy notice, served to both the consent gate and the public page.

Written against the Digital Personal Data Protection Rules, 2025 (G.S.R. 846(E),
13 November 2025), as held in this project's corpus. Rule 3 asks a notice to
stand on its own and give, in plain language, an itemised description of the
personal data, the specified purposes, and how to withdraw consent, exercise
rights and complain to the Board. The structure below follows that.

Under G.S.R. 843(E) of the same date, the sections and rules that impose these
duties commence eighteen months after publication. The notice is built to that
standard already rather than claiming the law requires it today.

Bump PRIVACY_NOTICE_VERSION whenever the substance changes: every account is
then asked to accept the new version on its next visit.
"""

from __future__ import annotations

PRIVACY_NOTICE_VERSION = "2026-11-04"

PERSONAL_DATA_ITEMS: tuple[tuple[str, str], ...] = (
    ("Account details", "Your name, email address and role."),
    ("Sign-in security", "A hash of your password, and if you turn on two-step sign-in, an encrypted authenticator secret and hashes of your recovery codes."),
    ("Signed-in devices", "A readable label such as “Firefox on Windows”, with the times the device was first and last seen. Your IP address and full browser string are not stored with it."),
    ("Your questions and answers", "What you ask, what the system answered, the sources it cited, and any rating or correction you give."),
    ("Organisation of your history", "Which conversations you pinned and the matter names you gave them."),
    ("Case material (police and advocate accounts)", "Case titles, documents you upload, the text extracted from them, recorded dates and compliance entries, and drafts generated from them."),
    ("Documents you attach to a question", "The text extracted from a document is used to answer that question and is not kept as a file. If you ask a follow-up, it travels with that request too."),
    ("Activity records", "A security log of actions on your account, such as sign-ins and exports. These do not contain the words of your questions."),
)

PURPOSES: tuple[str, ...] = (
    "To sign you in and keep your account secure.",
    "To answer your legal research questions from the indexed corpus and show the sources.",
    "To keep your conversation history and, for professional accounts, your case records, so you can return to them.",
    "To keep a security log, so that misuse of an account can be detected and investigated.",
)

WHAT_DOES_NOT_HAPPEN: tuple[str, ...] = (
    "Answers are generated by a language model running on the machine that hosts this installation. Your questions are not sent to an outside AI service.",
    "Your data is not sold, and is not used for advertising.",
    "Conversations and uploads are not added to the shared legal corpus or used to train a model.",
)

KNOWN_EXCEPTIONS: tuple[str, ...] = (
    "Voice input uses your browser’s speech recognition. Some browsers send that audio to their vendor. Typing avoids this.",
    "Opening a citation’s official source link takes you to that government website, which has its own privacy terms.",
)


def notice_document() -> dict[str, object]:
    return {
        "version": PRIVACY_NOTICE_VERSION,
        "personal_data": [
            {"item": item, "detail": detail} for item, detail in PERSONAL_DATA_ITEMS
        ],
        "purposes": list(PURPOSES),
        "what_does_not_happen": list(WHAT_DOES_NOT_HAPPEN),
        "known_exceptions": list(KNOWN_EXCEPTIONS),
    }
